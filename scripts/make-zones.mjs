// Generates hooks/zones.ts from the IANA time zone database, so the mod can map
// a time zone to its countries and hemisphere without any network access.
//
// Usage: node scripts/make-zones.mjs [zoneinfo directory]
// The directory defaults to /usr/share/zoneinfo and must hold zone1970.tab,
// zone.tab and tzdata.zi (shipped by the tzdata package on most systems).

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2] ?? '/usr/share/zoneinfo'
const read = name => readFileSync(join(dir, name), 'utf8').split('\n').filter(line => line && !line.startsWith('#'))

/** ISO 6709 "+4723+00832" -> latitude in degrees, rounded to 0.1. */
function latitude(coords) {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?[+-]/.exec(coords)
  if (!m) throw new Error(`bad coordinates ${coords}`)
  const deg = Number(m[2]) + Number(m[3]) / 60 + Number(m[4] ?? 0) / 3600
  return Math.round((m[1] === '-' ? -deg : deg) * 10) / 10
}

const zones = new Map()
// zone1970.tab: every country that uses a zone, coordinates of its main city.
for (const line of read('zone1970.tab')) {
  const [countries, coords, zone] = line.split('\t')
  zones.set(zone, { countries: countries.split(','), lat: latitude(coords) })
}
// zone.tab: the zone's own country first (Europe/Zurich -> CH), plus zones
// zone1970.tab merges away (Europe/Vaduz -> LI).
for (const line of read('zone.tab')) {
  const [country, coords, zone] = line.split('\t')
  const known = zones.get(zone)
  if (known) {
    known.countries = [country, ...known.countries.filter(c => c !== country)]
  } else {
    zones.set(zone, { countries: [country], lat: latitude(coords) })
  }
}
// tzdata.zi links: old names some systems still report (Asia/Calcutta -> Asia/Kolkata).
let links = 0
for (const line of read('tzdata.zi')) {
  const [kind, target, alias] = line.split(' ')
  if (kind === 'L' && zones.has(target) && !zones.has(alias)) {
    zones.set(alias, zones.get(target))
    links += 1
  }
}

const rows = [...zones.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([zone, z]) => `  '${zone}': ['${z.countries.join(',')}', ${z.lat}],`)
writeFileSync(
  new URL('../hooks/zones.ts', import.meta.url),
  `// Generated by scripts/make-zones.mjs from the IANA time zone database
// (zone1970.tab, zone.tab and the links in tzdata.zi). Do not edit by hand.
//
// Each zone maps to the countries that use it (ISO 3166, the zone's own
// country first) and the latitude of its main city, which gives the hemisphere.

export const ZONES: Record<string, [countries: string, latitude: number]> = {
${rows.join('\n')}
}
`,
)
console.log(`${zones.size} zones (${links} of them old names linked to current ones)`)
